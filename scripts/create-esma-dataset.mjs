function slugify(value) {
  return value.toLocaleLowerCase("tr-TR").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/ı/g, "i").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

const records = names.map(([arabic, name, shortMeaning], index) => ({
  order: index + 1,
  slug: slugify(name),
  arabic,
  name,
  transliteration: name,
  shortMeaning,
  meaning: `${name}, ${shortMeaning.toLocaleLowerCase("tr-TR")} Bu anlam, Allah hakkında düşünürken ilgili ilahî niteliği ve onun insan hayatındaki sorumluluk çağrışımını birlikte görmeye yardımcı olur.`,
  reflection: `${name} ismi, ${shortMeaning.toLocaleLowerCase("tr-TR")} fikri üzerinde sakinlikle düşünmeye davet eder. Bu tefekkür, varlık, emanet ve sorumluluk duygusuna daha dikkatli bakmak için bir alan açabilir.`,
  humanReflection: `Bu isim, insanın ${shortMeaning.toLocaleLowerCase("tr-TR")} düşüncesiyle umut, güven, ölçü ve sorumluluk kavramlarını yeniden ele almasına alan açar. Günlük hayatın kararlarında daha dikkatli ve merhametli bir bakış geliştirmeyi hatırlatabilir.`,
  quranReferences: [],
  relatedTopicIds: [],
  sources: [source, reference],
  reviewStatus: "sourceChecked",
}));

if (records.length !== 99 || new Set(records.map(record => record.slug)).size !== 99) throw new Error("Expected 99 unique Esma records");
await writeFile("src/data/esma/published.json", JSON.stringify(records, null, 2));
